-- Run as ACCOUNTADMIN (or a role that can create warehouses/databases/roles). Edit names if needed.
CREATE WAREHOUSE IF NOT EXISTS ATMOSYNC_WH WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS ATMOSYNC;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.RAW;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.ANALYTICS;
CREATE ROLE IF NOT EXISTS ATMOSYNC_ROLE;                       -- used by Python, dbt and Tableau
CREATE ROLE IF NOT EXISTS ATMOSYNC_VIEWER;                     -- read-only BI users (week-1 "access roles")
GRANT USAGE, OPERATE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_ROLE;
GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_VIEWER;
GRANT ALL ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE ATMOSYNC TO ROLE ATMOSYNC_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE ATMOSYNC TO ROLE ATMOSYNC_ROLE;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_VIEWER;
GRANT USAGE ON SCHEMA ATMOSYNC.ANALYTICS TO ROLE ATMOSYNC_VIEWER;
GRANT SELECT ON ALL TABLES IN SCHEMA ATMOSYNC.ANALYTICS TO ROLE ATMOSYNC_VIEWER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATMOSYNC.ANALYTICS TO ROLE ATMOSYNC_VIEWER;
