-- Raw landing tables. Column names/types must match what dbt sources (models/sources.yml) expect.
USE ROLE ATMOSYNC_ROLE; USE WAREHOUSE ATMOSYNC_WH; USE SCHEMA ATMOSYNC.RAW;

CREATE TABLE IF NOT EXISTS RAW_SENSOR_EVENTS (
    EVENT_ID     VARCHAR       NOT NULL,
    EVENT_TS     TIMESTAMP_NTZ,
    PAYLOAD      VARIANT       NOT NULL,            -- original JSON message from Kafka
    SOURCE       VARCHAR,
    INGESTED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
) CLUSTER BY (TO_DATE(EVENT_TS), EVENT_ID);          -- time-range pruning for monitoring queries

CREATE TABLE IF NOT EXISTS RAW_LOCATIONS (LOCATION_ID VARCHAR, NAME VARCHAR, LATITUDE FLOAT, LONGITUDE FLOAT,
    IS_MARKET BOOLEAN, LOCATION_TYPE VARCHAR, DATA_ORIGIN VARCHAR);
CREATE TABLE IF NOT EXISTS RAW_CONTAINERS (CONTAINER_ID VARCHAR, SENSOR_ID VARCHAR, CONTAINER_TYPE VARCHAR,
    SETPOINT_TEMP_C FLOAT, DATA_ORIGIN VARCHAR);
CREATE TABLE IF NOT EXISTS RAW_COMMODITIES (COMMODITY_ID VARCHAR, DISPLAY_NAME VARCHAR, TEMP_MIN_C FLOAT, TEMP_MAX_C FLOAT,
    TEMP_BEST_C FLOAT, RH_MIN_PCT FLOAT, RH_MAX_PCT FLOAT, BASE_SHELF_LIFE_DAYS FLOAT, SOURCE VARCHAR);
CREATE TABLE IF NOT EXISTS RAW_SHIPMENTS (SHIPMENT_ID VARCHAR, CONTAINER_ID VARCHAR, COMMODITY_ID VARCHAR, QUANTITY_KG FLOAT,
    ORIGIN_ID VARCHAR, PLANNED_DESTINATION_ID VARCHAR, DEPARTURE_TS VARCHAR, PLANNED_ARRIVAL_TS VARCHAR, ROUTE_KM FLOAT,
    PRE_LOADING_LIFE_CONSUMED FLOAT, DATA_ORIGIN VARCHAR);
CREATE TABLE IF NOT EXISTS RAW_MARKET_PRICES (PRICE_DATE DATE, MARKET_ID VARCHAR, COMMODITY_ID VARCHAR, PRICE_MIN_USD_KG FLOAT,
    PRICE_MAX_USD_KG FLOAT, PRICE_MODAL_USD_KG FLOAT, DATA_ORIGIN VARCHAR);
