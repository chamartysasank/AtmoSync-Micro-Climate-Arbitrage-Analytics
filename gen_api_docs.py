"""Generate docs/reference/python_api.md (module overview + public functions/classes) from docstrings and signatures.
AtmoSync exposes a PYTHON API only (there is no REST service); run:  python scripts/gen_api_docs.py"""
import importlib, inspect, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))

BATCH = {"analytics.anomaly": "01", "app.context": "01", "app.views": "01", "analytics.health": "02", "common.store": "02", "analytics.forecast": "03", "analytics.routes": "04",
         "analytics.market": "05", "analytics.alert_center": "06", "ingestion.quality": "07", "simulator.lab": "08", "analytics.reporting": "09", "common.monitoring": "10"}
MODULES = ["common.config", "common.store", "common.monitoring", "ingestion.cleaning", "ingestion.replay", "ingestion.quality", "ingestion.local_warehouse", "ingestion.hab_prices",
           "simulator.iot_simulator", "simulator.lab", "analytics.engine", "analytics.geo", "analytics.pipeline", "analytics.anomaly", "analytics.health", "analytics.forecast",
           "analytics.routes", "analytics.market", "analytics.alert_center", "analytics.alerts", "analytics.reporting", "analytics.export_tableau",
           "streaming.validation", "streaming.producer", "streaming.consumer", "streaming.sinks", "app.context", "app.views"]


def first(doc: str | None) -> str:
    return (doc or "").strip().split("\n\n")[0].replace("\n", " ").strip()


def main():
    out = ["# Python API reference", "", "*Generated by `scripts/gen_api_docs.py` from docstrings and signatures. AtmoSync has a Python API only; there is no REST/HTTP service.*",
           "", "## Module overview", "", "| Module | Phase / batch | Purpose |", "|---|---|---|"]
    mods = []
    for name in MODULES:
        m = importlib.import_module(name); mods.append(m)
        out.append(f"| `{name}` | {'Batch ' + BATCH[name] if name in BATCH else 'Phase 1'} | {first(m.__doc__)[:160]} |")
    out += ["", "## Public functions and classes", ""]
    for m in mods:
        items = [(n, o) for n, o in inspect.getmembers(m) if not n.startswith("_") and (inspect.isfunction(o) or inspect.isclass(o)) and getattr(o, "__module__", "") == m.__name__]
        if not items: continue
        out += [f"### `{m.__name__}`", ""]
        for n, o in sorted(items, key=lambda x: inspect.getsourcelines(x[1])[1]):
            try: sig = str(inspect.signature(o))
            except (TypeError, ValueError): sig = "(...)"
            out.append(f"- **`{n}{sig}`** — {first(o.__doc__) or '(no description)'}")
        out.append("")
    (ROOT / "docs" / "reference" / "python_api.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/reference/python_api.md")


if __name__ == "__main__":
    main()
