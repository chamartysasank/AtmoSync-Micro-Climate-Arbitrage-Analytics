"""Generate docs/reference/configuration.md from config/settings.yaml and config/features/*.yaml (keys, defaults, comments).
Run:  python scripts/gen_config_reference.py"""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
LINE = re.compile(r"^(\s*)([A-Za-z0-9_\-]+):\s*(.*?)\s*(?:#\s*(.*))?$")


def rows(path: Path):
    stack, out = [], []
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.strip().startswith("#"): continue
        m = LINE.match(raw)
        if not m: continue
        indent, key, val, comment = len(m.group(1)), m.group(2), m.group(3), m.group(4) or ""
        while stack and stack[-1][0] >= indent: stack.pop()
        stack.append((indent, key))
        if val and not val.startswith("#"):
            out.append((".".join(k for _, k in stack), val.rstrip(), comment))
    return out


def main():
    files = [ROOT / "config" / "settings.yaml"] + sorted((ROOT / "config" / "features").glob("*.yaml")) + [ROOT / "config" / "commodities.yaml"]
    md = ["# Configuration reference", "", "*Generated by `scripts/gen_config_reference.py`. Values tagged `[SOURCE]` are backed by a cited publication; `[ASSUMPTION]` values are project defaults to review with your mentor. "
          "`config/features/*.yaml` are merged automatically by `common/config.py::load_settings` under their own top-level keys. dbt reads its own copies in `dbt_project/dbt_project.yml` (kept in sync by a test).*", ""]
    env = ["`KAFKA_BOOTSTRAP_SERVERS`, `SNOWFLAKE_ACCOUNT|USER|PASSWORD|ROLE|WAREHOUSE|DATABASE|SCHEMA`, `SLACK_WEBHOOK_URL`, `SMTP_HOST|PORT|USER|PASSWORD`, `ALERT_EMAIL_TO` (see `.env.example`); "
           "`ATMOSYNC_DUCKDB` overrides the local DuckDB file for dbt **and** for the Phase 2 app tables (`common/store.py`); `LOG_LEVEL`."]
    for f in files:
        md += [f"## `{f.relative_to(ROOT)}`", "", "| Key | Default | Notes |", "|---|---|---|"]
        md += [f"| `{k}` | `{v.replace('|', chr(92) + '|')}` | {c.replace('|', chr(92) + '|')} |" for k, v, c in rows(f)]
        md.append("")
    md += ["## Environment variables", ""] + env + [""]
    (ROOT / "docs" / "reference" / "configuration.md").write_text("\n".join(md), encoding="utf-8"); print("wrote docs/reference/configuration.md")


if __name__ == "__main__":
    main()
